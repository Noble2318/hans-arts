def get_translations(lang):
    """Return every string for `lang`, filling any missing key from English.

    Use this in your context processor instead of TRANSLATIONS[lang], so a
    key missing from one language shows English text rather than nothing.
    """
    return {**TRANSLATIONS['en'], **TRANSLATIONS.get(lang, {})}


def get_text(lang, key):
    return get_translations(lang).get(key, key)


def missing_keys():
    """Return {language: [keys]} for any language missing a key that English has."""
    english = set(TRANSLATIONS['en'])
    return {
        lang: sorted(english - set(strings))
        for lang, strings in TRANSLATIONS.items()
        if english - set(strings)
    }